"""Parser for Claude Code JSONL transcripts.

This is the first (and currently only) supported source format. SWE-chat ships
raw Claude Code transcripts as ``transcripts/<session_id>.jsonl`` and Claude Code
stores its own (sub)agent transcripts in the same format, so one parser serves
both the natural and the controlled population.

Each JSONL line is one entry. ``user`` / ``assistant`` entries carry a
``message`` whose ``content`` is either a string or a list of content blocks
(``text``, ``thinking``, ``tool_use``, ``tool_result``, ...). Every block becomes
one :class:`~tracecontract.schemas.Event` with a stable id derived from the line
number and block index, so evidence spans can point at exact source locations.

Log text is treated strictly as data: nothing in it is executed or interpreted
as an instruction.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from ..schemas import Author, Event, EventKind, Population, Session, SourceRef, sha256_bytes

SOURCE_FORMAT = "claude_code_jsonl"

# Text that arrives in the user role but was produced by the harness, not typed.
_INJECTED_PREFIXES = (
    "<command-name>",
    "<command-message>",
    "<command-args>",
    "<local-command-stdout>",
    "<local-command-stderr>",
    "<local-command-caveat>",
    "<system-reminder>",
    "<user-prompt-submit-hook>",
    "<bash-input>",
    "<bash-stdout>",
    "<bash-stderr>",
    "<task-notification>",
    "Caveat: The messages below were generated by the user while running local commands",
    "This session is being continued from a previous conversation",
)
_INTERRUPT_RE = re.compile(r"^\[Request interrupted by user[^\]]*\]\s*$")


def _event_id(session_id: str, line: int, block: int) -> str:
    return f"{session_id}/L{line:06d}.{block:02d}"


def _tool_result_text(content: Any) -> str:
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for b in content:
            if isinstance(b, dict) and b.get("type") == "text":
                parts.append(str(b.get("text", "")))
            elif isinstance(b, dict):
                parts.append(f"<{b.get('type', 'block')}>")
        return "\n".join(parts)
    return "" if content is None else str(content)


def classify_user_text(text: str, *, is_meta: bool = False) -> EventKind:
    """Classify text found in a ``user`` entry (proposal-level heuristic)."""
    stripped = text.lstrip()
    if is_meta:
        return EventKind.system_injected
    if _INTERRUPT_RE.match(stripped):
        return EventKind.user_interrupt
    if stripped.startswith(_INJECTED_PREFIXES):
        return EventKind.system_injected
    return EventKind.user_prompt


def parse_claude_code_jsonl(
    path: str | Path,
    *,
    session_id: str | None = None,
    population: Population,
    source: str,
    source_revision: str | None = None,
    user_author: Author | None = None,
    include_sidechains: bool = False,
    relpath: str | None = None,
) -> Session:
    """Parse a Claude Code JSONL transcript into a :class:`Session`.

    ``user_author`` defaults to ``human`` for the natural population and
    ``scripted_user`` for the controlled population. Sidechain (subagent) entries
    are skipped unless ``include_sidechains`` is true.
    """
    path = Path(path)
    raw = path.read_bytes()
    if user_author is None:
        user_author = Author.scripted_user if population == Population.controlled else Author.human
        if population == Population.fixture:
            user_author = Author.scripted_user
    rel = relpath or path.name

    events: list[Event] = []
    meta: dict[str, Any] = {"cli_versions": set(), "cwd": set(), "git_branch": set(), "models": set()}
    sid = session_id
    bad_lines: list[int] = []

    def add(**kw: Any) -> None:
        events.append(Event(index=len(events), **kw))

    for lineno, line in enumerate(raw.decode("utf-8", errors="replace").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            entry = json.loads(line)
        except json.JSONDecodeError:
            bad_lines.append(lineno)
            continue
        if not isinstance(entry, dict):
            bad_lines.append(lineno)
            continue
        etype = entry.get("type")
        if sid is None and entry.get("sessionId"):
            sid = str(entry["sessionId"])
        if entry.get("isSidechain") and not include_sidechains:
            continue
        for key, mk in (("version", "cli_versions"), ("cwd", "cwd"), ("gitBranch", "git_branch")):
            if entry.get(key):
                meta[mk].add(str(entry[key]))
        ts = entry.get("timestamp")
        native = entry.get("uuid")
        side = bool(entry.get("isSidechain"))
        msg = entry.get("message")
        if etype not in ("user", "assistant") or not isinstance(msg, dict):
            # Metadata entries (summaries, snapshots, queue operations, ...) are kept as
            # metadata events only when they carry text a reviewer might need.
            if etype in ("summary",) and entry.get("summary"):
                add(
                    event_id=_event_id(sid or "unknown", lineno, 0),
                    session_id=sid or "unknown",
                    kind=EventKind.metadata,
                    author=Author.harness,
                    timestamp=ts,
                    text=str(entry.get("summary")),
                    source=SourceRef(path=rel, line=lineno, block=0, native_id=native),
                    is_sidechain=side,
                )
            continue
        content = msg.get("content")
        if etype == "assistant" and msg.get("model"):
            meta["models"].add(str(msg["model"]))
        blocks: list[Any] = content if isinstance(content, list) else [content]
        for bi, block in enumerate(blocks):
            eid = _event_id(sid or "unknown", lineno, bi)
            src = SourceRef(path=rel, line=lineno, block=bi, native_id=native)
            common = dict(event_id=eid, session_id=sid or "unknown", timestamp=ts, source=src, is_sidechain=side)
            if isinstance(block, str) or block is None:
                text = block or ""
                if etype == "user":
                    kind = classify_user_text(text, is_meta=bool(entry.get("isMeta")))
                    author = user_author if kind in (EventKind.user_prompt, EventKind.user_interrupt) else Author.harness
                    add(kind=kind, author=author, text=text, **common)
                else:
                    add(kind=EventKind.assistant_text, author=Author.agent, text=text, **common)
                continue
            if not isinstance(block, dict):
                continue
            btype = block.get("type")
            if btype == "text":
                text = str(block.get("text", ""))
                if etype == "user":
                    kind = classify_user_text(text, is_meta=bool(entry.get("isMeta")))
                    author = user_author if kind in (EventKind.user_prompt, EventKind.user_interrupt) else Author.harness
                    add(kind=kind, author=author, text=text, **common)
                else:
                    add(kind=EventKind.assistant_text, author=Author.agent, text=text, **common)
            elif btype == "thinking":
                add(kind=EventKind.assistant_thinking, author=Author.agent, text=str(block.get("thinking", "")), **common)
            elif btype == "tool_use":
                tin = block.get("input")
                add(
                    kind=EventKind.tool_call,
                    author=Author.agent,
                    text=json.dumps(tin, sort_keys=True, ensure_ascii=False) if tin is not None else "",
                    tool_name=str(block.get("name")),
                    tool_call_id=block.get("id"),
                    tool_input=tin if isinstance(tin, dict) else {"_raw": tin},
                    **common,
                )
            elif btype == "tool_result":
                add(
                    kind=EventKind.tool_result,
                    author=Author.tool,
                    text=_tool_result_text(block.get("content")),
                    tool_call_id=block.get("tool_use_id"),
                    is_error=bool(block.get("is_error")) if block.get("is_error") is not None else None,
                    **common,
                )
            else:
                add(kind=EventKind.metadata, author=Author.harness, text=f"<{btype}>", **common)

    if sid is None:
        raise ValueError(f"{path}: no sessionId found and none supplied")
    # Events parsed before the sessionId was discovered carry "unknown"; rewrite.
    fixed = []
    for e in events:
        if e.session_id == "unknown":
            e = e.model_copy(update={"session_id": sid, "event_id": e.event_id.replace("unknown/", f"{sid}/", 1)})
        fixed.append(e)
    metadata = {k: sorted(v) for k, v in meta.items()}
    metadata["bad_lines"] = bad_lines
    return Session(
        session_id=sid,
        population=population,
        source=source,
        source_revision=source_revision,
        source_format=SOURCE_FORMAT,
        agent="Claude Code",
        trace_sha256=sha256_bytes(raw),
        events=fixed,
        metadata=metadata,
    )
